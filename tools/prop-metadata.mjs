// Regenerate worker-safe prop bounds after exporting assets: node tools/prop-metadata.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

export function assetMetadata(directory) {
  const out = [];
  for (const file of ['props.glb', 'clutter.glb', 'themes.glb', 'items/treasure_chest.glb']) {
    const b = readFileSync(resolve(directory, file));
    const j = JSON.parse(b.subarray(20, 20 + b.readUInt32LE(12)));
    for (const i of j.scenes[j.scene || 0].nodes) {
      const root = j.nodes[i], positions = [];
      // roots have baked transforms; moving parts (the chest's lid) only sit at their pivot
      const visit = (n, at = [0, 0, 0]) => {
        if (n.matrix || n.rotation || n.scale || (n === root && n.translation)) throw Error('Expected baked prop transforms: ' + n.name);
        at = at.map((v, k) => v + (n.translation?.[k] ?? 0));
        if (n.mesh != null) for (const p of j.meshes[n.mesh].primitives) {
          const a = j.accessors[p.attributes.POSITION];
          positions.push({ min: a.min.map((v, k) => v + at[k]), max: a.max.map((v, k) => v + at[k]) });
        }
        for (const child of n.children || []) visit(j.nodes[child], at);
      };
      visit(root);
      const [set, ...rest] = root.name.split('_');
      const min = [0, 1, 2].map(k => Math.min(...positions.map(p => p.min[k])));
      const max = [0, 1, 2].map(k => Math.max(...positions.map(p => p.max[k])));
      out.push({ name: root.name, set, base: rest.slice(0, -1).join('_'),
        ...root.extras, height: max[1], minY: min[1], maxY: max[1], bounds: [min[0], min[2], max[0], max[2]] });
    }
  }
  return out;
}

if (process.argv[1] === import.meta.filename) {
  const directory = resolve(import.meta.dirname, '../assets');
  const metadata = assetMetadata(directory);
  writeFileSync(resolve(import.meta.dirname, '../src/core/propmetadata.js'),
    '// Generated by tools/prop-metadata.mjs; do not edit by hand.\nexport const PROP_METADATA = [\n'
    + metadata.map(p => '  ' + JSON.stringify(p)).join(',\n') + '\n];\n');
  console.log('Generated metadata for', metadata.length, 'models');
}
